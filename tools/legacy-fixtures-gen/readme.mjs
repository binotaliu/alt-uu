import fs from 'node:fs';
import { OUT, registry } from './lib.mjs';

const byDomain = {};
for (const r of registry) (byDomain[r.domain] ??= []).push(r);
const order = ['course', 'school-portal', 'discuss', 'moderation', 'nou-tools', 'app-status', 'study-time', 'data-portability', 'hungu-transport', 'diagnostics'];
const esc = (s) => String(s).replaceAll('|', '\\|').replaceAll('\n', ' ');
const test = (src) => (src.startsWith('SYNTHETIC') ? `**${esc(src)}**` : '`' + esc(src) + '`');

let md = `# Core test fixtures

Upstream payloads (HTML / XML / JSON / text) and expected outputs extracted from the legacy Laravel/Pest test-suite
(\`/Users/binota/Developer/alt-uu-legacy/tests\`, a worktree of \`main\`). The TypeScript ports of the PHP
parsers/actions must reproduce these results ("parity").

## Layout and file kinds

\`\`\`
<domain>/<name>.(html|xml|json|txt)   upstream payload / request body used by the legacy test (input)
<domain>/<name>.<suffix>.<ext>        extra payloads of a multi-payload fixture (e.g. .homework.html + .forum.html)
<domain>/<name>.expected.json         what the legacy Pest test asserted
<domain>/<name>.golden.json           full output captured by running the REAL PHP code (where useful)
\`\`\`

Load them with \`index.ts\`: \`loadFixture(domain, name)\`, \`loadFixtureBytes\`, \`loadFixtureJson\`, \`loadExpected\`,
\`loadGolden\`, \`listFixtures\`. (Test-only, uses \`node:fs\`.)

### \`*.expected.json\`

\`{ source, phpClass, note?, cases: [{ name, input?, partial?, expected }] }\`

* \`name\` is the Pest test title; \`source\` is \`<legacy test file>:<line>\` relative to \`tests/\`.
* \`"partial": true\` means the Pest test only asserted a subset: \`expected\` then lists **only** the asserted fields.
  Without \`partial\`, \`expected\` is the complete asserted value.
* Keys in \`expected\` objects such as \`"items[0]"\`, \`"grade.courseName"\` or \`"nodes[1].isRead"\` are JSON-path-like shorthands
  for the asserted path (Laravel \`assertJsonPath\` style); the value is the asserted value.
* Matcher vocabulary used inside \`expected\` values (mirrors Pest's \`toContain\` / \`not->toContain\` etc.):
  \`{ "contains": [...] }\`, \`{ "notContains": [...] }\`, \`{ "startsWith": "user#", "notContains": ... }\`, \`{ "equals": ... }\`,
  \`{ "isValidUtf8": true }\`, \`{ "nonEmpty": true }\`.
* Material proxy URLs: legacy rewrote same-host resources to \`route('material.content', encodedUrl)\`.
  \`{ "proxyOf": "<original url>" }\` means "the proxy URL wrapping this original URL" (\`MaterialProxyUrl::encode\` =
  base64url without padding of the URL); \`{ "srcAttrProxyOf": ... }\` is the same inside a \`src="..."\` attribute.
  The golden files show the concrete legacy form (\`http://localhost/material-proxy/<base64url>\`). The RN port will define
  its own proxy scheme; what must match is the **original URL that is wrapped** and which URLs get rewritten.
* \`{ "staticsBaseUrlConfig": "/youtube-embed.html?v=..." }\` = \`config('services.statics.base_url')\` + that suffix (golden shows the production default).
* Some cases describe behaviour that has no payload (e.g. reauth-retry, base-url routing); their \`input\` documents the setup.

### \`*.golden.json\`

\`{ generatedBy, phpClass, cases: [{ name, input, output, upstreamRequests? }] }\` generated by the PHP runner
(\`scratchpad/fixtures-gen/GoldenTest.php\`, a PHPUnit class that boots the legacy app with an in-memory SQLite DB, fakes upstream
HTTP with the fixture files and calls the real controllers/actions). \`output\` is what the Vue frontend received
(ViewModel \`toArray()\`, camelCase) -- for endpoint goldens \`{ status, json }\`. \`upstreamRequests\` (mutations, moderation, login)
records the HTTP calls the PHP made (method, URL, body) -- the body strings are PHP \`json_encode\` output (non-ASCII is \`\\uXXXX\`-escaped).
Session used by endpoint goldens: Hungu base \`https://uu.nou.edu.tw\` (ticket \`ticket-1\`), school portal base \`https://nouapp.nou.edu.tw\`.

Non-determinism notes: \`login-success.golden.json\` masks the AES-encrypted username/password (random IV); moderation report
\`client_hash\`/\`site_hash\` depend on the legacy test environment (APP_KEY); the data export golden pins \`exportedAt\` with a frozen clock.

Fixtures marked **SYNTHETIC** have no legacy Pest coverage: the upstream sample was written from the PHP parsing code, and only
the golden (real PHP output) is authoritative.

## Index
`;
for (const d of order) {
    const rs = byDomain[d];
    if (!rs) continue;
    md += `\n### ${d} (${rs.length})\n\n| Fixture | Files | Legacy source (tests/) | PHP class under test | Notes |\n|---|---|---|---|---|\n`;
    for (const r of rs) {
        md += `| \`${r.name}\` | ${r.files.map((f) => '`' + f.slice(r.name.length) + '`').join(' ')} | ${test(r.source)} | \`${esc(r.cls)}\` | ${esc(r.note)} |\n`;
    }
}
md += `
## Legacy tests with no fixtures (out of scope or no payload)

Behaviour/UI/native tests that have no upstream payload to port: \`Feature/ArchTest\`, \`NativeShellPatchMapTest\`,
\`CleanupNativephpExcludeCommandTest\`, \`ExternalServiceUnavailableTest\`, \`Packages/MediaPlayerPluginTest\`, \`Unit/MediaSessionPluginTest\`,
\`Unit/DownloadAttachmentJobTest\`, \`AttachmentDownload/*\`, \`Subscription/SubscriptionTest\`, \`Account/*\`, \`Activity/AccountActivityTest\`,
\`AppPreference/*\`, \`MaterialPreference/*\`, \`Auth/SessionProfileControllerTest\`, \`Diagnostics/*\` other than the redactor
(recorder, recording toggle, upstream-call recording, connectivity, silent degradation, material source inspection, exception renderer, log API),
and all \`Browser/*\` tests (UI flows; their only upstream payloads that matter are duplicated in the fixtures above).
`;
fs.writeFileSync(`${OUT}/README.md`, md);
