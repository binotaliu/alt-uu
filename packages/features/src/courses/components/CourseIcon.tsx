export type CourseIconName = keyof typeof extraIconPaths | IconName;

export interface CourseIconProps {
    name: CourseIconName;
    size?: number;
    className?: string;
}

function isExtraIcon(
    name: CourseIconName,
): name is keyof typeof extraIconPaths {
    return name in extraIconPaths;
}

/** `@altuu/ui` Icon plus the few extra Heroicons the course screens use. */
export function CourseIcon({ name, size = 20, className }: CourseIconProps) {
    if (!isExtraIcon(name)) {
        return <Icon name={name} size={size} className={className} />;
    }

    return (
        <StyledSvg
            width={size}
            height={size}
            viewBox="0 0 24 24"
            fill="none"
            stroke="currentColor"
            strokeWidth={1.5}
            className={className}
            accessibilityElementsHidden
            importantForAccessibility="no-hide-descendants"
        >
            {extraIconPaths[name].map((d) => (
                <Path
                    key={d}
                    d={d}
                    strokeLinecap="round"
                    strokeLinejoin="round"
                />
            ))}
        </StyledSvg>
    );
}
