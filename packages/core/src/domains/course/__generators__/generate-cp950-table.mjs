/**
 * Generates ../encoding/cp950Table.generated.ts from iconv-lite's CP950 (Big5)
 * mapping. Run from the repo root:
 *   node packages/core/src/domains/course/__generators__/generate-cp950-table.mjs
 * The output holds one UTF-16 code unit per double-byte cell (lead
 * 0x81-0xFE x trail 0x40-0x7E / 0xA1-0xFE); U+FFFD marks unmapped cells.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import iconv from 'iconv-lite';

const here = path.dirname(fileURLToPath(import.meta.url));
const trails = [];
for (let byte = 0x40; byte <= 0x7e; byte++) trails.push(byte);
for (let byte = 0xa1; byte <= 0xfe; byte++) trails.push(byte);

let table = '';
for (let lead = 0x81; lead <= 0xfe; lead++) {
    for (const trail of trails) {
        const decoded = iconv.decode(Buffer.from([lead, trail]), 'cp950');
        table += decoded.length === 1 ? decoded : '�';
    }
}

const source = `// Generated by ../__generators__/generate-cp950-table.mjs. Do not edit.
export const CP950_TRAIL_COUNT = ${trails.length};
export const CP950_TABLE =
    ${JSON.stringify(table)};
`;
fs.writeFileSync(
    path.join(here, '..', 'encoding', 'cp950Table.generated.ts'),
    source,
);
console.log('cells', table.length);
