/**
 * Embeds the drizzle-kit generated SQL into `src/db/migrations.generated.ts`
 * so migrations ship inside the JS bundle (no .sql imports in Metro).
 * Run after `drizzle-kit generate`: `npm run db:generate -w @altuu/core`.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'db');
const journal = JSON.parse(
  readFileSync(join(root, 'migrations', 'meta', '_journal.json'), 'utf8'),
);

const migrations = {};
for (const entry of journal.entries) {
  const file = readdirSync(join(root, 'migrations')).find(
    (name) => name === `${entry.tag}.sql`,
  );
  if (!file) {
    throw new Error(`Missing SQL file for ${entry.tag}`);
  }
  migrations[`m${String(entry.idx).padStart(4, '0')}`] = readFileSync(
    join(root, 'migrations', file),
    'utf8',
  );
}

const output = `
// Generated by scripts/build-migrations.mjs. Do not edit.
import type { MigrationBundle } from './migrate';

export const migrationBundle: MigrationBundle = ${JSON.stringify({ journal, migrations }, null, 4)};
`;
writeFileSync(join(root, 'migrations.generated.ts'), output);
